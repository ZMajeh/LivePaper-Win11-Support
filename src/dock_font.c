// The first character of the table and the number of the characters.
#define FONT_FIRST 32
#define FONT_COUNT 95

int FontDrawChar(SDL_Renderer *renderer, char c, int x, int y, int scale,
                 uint8_t r, uint8_t g, uint8_t b) {
    unsigned char code = (unsigned char)c;
    if (code < FONT_FIRST || code >= FONT_FIRST + FONT_COUNT) {
        // A character that is not in the table is drawn as a space.
        code = FONT_FIRST;
    }
    const unsigned char *glyph = g_font + (code - FONT_FIRST) * 5;

    SDL_SetRenderDrawColor(renderer, r, g, b, 255);
    for (int col = 0; col < 5; col++) {
        unsigned char bits = glyph[col];
        for (int row = 0; row < 7; row++) {
            if (!(bits & (1 << row))) continue;
            SDL_Rect pixel = { x + col * scale, y + row * scale, scale, scale };
            SDL_RenderFillRect(renderer, &pixel);
        }
    }
    return 5 * scale;
}

int FontTextWidth(const char *text, int scale) {
    if (!text) return 0;
    int length = (int)strlen(text);
    if (length == 0) return 0;
    // The last character has no space after it.
    return (length * FONT_ADVANCE - 1) * scale;
}

void FontDrawText(SDL_Renderer *renderer, const char *text, int x, int y,
                  int scale, uint8_t r, uint8_t g, uint8_t b) {
    if (!text) return;
    int cursor = x;
    for (const char *c = text; *c; c++) {
        FontDrawChar(renderer, *c, cursor, y, scale, r, g, b);
        cursor += FONT_ADVANCE * scale;
    }
}
